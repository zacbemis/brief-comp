#include "codegen/c.h"
#include "runtime_text.h"

static void line(FILE *out, Span span) {
  if (!span.file)
    return;
  fprintf(out, "#line %zu \"", source_position(span.file, span.start).line);
  for (const unsigned char *p = (const unsigned char *)span.file->path; *p;
       p++) {
    if (*p == '\\' || *p == '"' || *p == '?')
      fprintf(out, "\\%c", *p);
    else if (*p < 32 || *p >= 127)
      fprintf(out, "\\%03o", (unsigned int)*p);
    else
      fputc(*p, out);
  }
  fputs("\"\n", out);
}
// Fixed-width octal escapes cannot absorb a following digit, unlike \\xNN.
// Keep ordinary text readable while preserving the exact UTF-8/control bytes.
static void string_literal(FILE *out, const unsigned char *bytes,
                           size_t length) {
  fputc('"', out);
  for (size_t i = 0; i < length; i++) {
    unsigned char c = bytes[i];
    switch (c) {
    case '\n':
      fputs("\\n", out);
      break;
    case '\r':
      fputs("\\r", out);
      break;
    case '\t':
      fputs("\\t", out);
      break;
    case '\\':
      fputs("\\\\", out);
      break;
    case '"':
      fputs("\\\"", out);
      break;
    case '?':
      fputs("\\?", out);
      break; // Prevent C11 trigraphs.
    default:
      if (c < 32 || c >= 127)
        fprintf(out, "\\%03o", (unsigned int)c);
      else
        fputc(c, out);
      break;
    }
  }
  fputc('"', out);
}
int emit_c(FILE *out, const IrProgram *p) {
  fputs("/* Generated by Brief. Self-contained C11. */\n", out);
  fwrite(brief_runtime_text, 1, sizeof(brief_runtime_text) - 1, out);
  fputc('\n', out);
  for (size_t i = 0; i < p->count; i++)
    fprintf(out, "void brf_%s(void);\n", p->functions[i].name);
  for (size_t i = 0; i < p->count; i++) {
    const IrFunction *f = &p->functions[i];
    line(out, f->span);
    fprintf(out, "void brf_%s(void) {\n", f->name);
    for (size_t j = 0; j < f->count; j++) {
      const IrInstruction *in = &f->instructions[j];
      line(out, in->span);
      switch (in->op) {
      case IR_STRING: {
        size_t id = in->as.string.result;
        fprintf(out, "  static const unsigned char brt_bytes_%zu[] = ", id);
        string_literal(out, in->as.string.bytes, in->as.string.length);
        fputs(";\n", out);
        fprintf(out,
                "  static const brt_string brt_literal_%zu = {%zu, "
                "brt_bytes_%zu};\n",
                id, in->as.string.length, id);
        fprintf(out,
                "  const brt_string *brt_tmp_%zu = &brt_literal_%zu;\n  "
                "(void)brt_tmp_%zu;\n",
                id, id, id);
        break;
      }
      case IR_CALL:
        if (in->as.call.builtin)
          fprintf(out, "  brt_print(brt_tmp_%zu);\n", in->as.call.argument);
        else
          fprintf(out, "  brf_%s();\n",
                  p->functions[in->as.call.function].name);
        break;
      case IR_RETURN:
        fputs("  return;\n", out);
        break;
      }
    }
    fputs("}\n\n", out);
  }
  fputs("#line 1 \"<brief entry>\"\nint main(void) {\n", out);
  fprintf(out, "  brf_%s();\n", p->functions[p->entry].name);
  fputs("  if (fflush(stdout) == EOF) {\n"
        "    fputs(\"error: cannot flush standard output\\n\", stderr);\n"
        "    return 1;\n  }\n  return 0;\n}\n",
        out);
  return !ferror(out);
}
