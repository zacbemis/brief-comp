#include "codegen/c.h"
#include "runtime_text.h"
#include <inttypes.h>

static void line(FILE *out, Span span) {
  if (!span.file)
    return;
  fprintf(out, "#line %zu \"", source_position(span.file, span.start).line);
  for (const unsigned char *p = (const unsigned char *)span.file->path; *p;
       p++) {
    if (*p == '\\' || *p == '"' || *p == '?')
      fprintf(out, "\\%c", *p);
    else if (*p < 32 || *p >= 127)
      fprintf(out, "\\%03o", (unsigned int)*p);
    else
      fputc(*p, out);
  }
  fputs("\"\n", out);
}
// Fixed-width octal escapes cannot absorb a following digit, unlike \\xNN.
// Keep ordinary text readable while preserving the exact UTF-8/control bytes.
static void string_literal(FILE *out, const unsigned char *bytes,
                           size_t length) {
  fputc('"', out);
  for (size_t i = 0; i < length; i++) {
    unsigned char c = bytes[i];
    switch (c) {
    case '\n':
      fputs("\\n", out);
      break;
    case '\r':
      fputs("\\r", out);
      break;
    case '\t':
      fputs("\\t", out);
      break;
    case '\\':
      fputs("\\\\", out);
      break;
    case '"':
      fputs("\\\"", out);
      break;
    case '?':
      fputs("\\?", out);
      break; // Prevent C11 trigraphs.
    default:
      if (c < 32 || c >= 127)
        fprintf(out, "\\%03o", (unsigned int)c);
      else
        fputc(c, out);
      break;
    }
  }
  fputc('"', out);
}
static const char *ctype(SemaTypeKind kind) {
  static const char *names[] = {
      "void",    "void",     "void",     "void",    "_Bool",
      "uint8_t", "int16_t",  "uint16_t", "int32_t", "uint32_t",
      "int64_t", "uint64_t", "float",    "double",  "const brt_string *"};
  return names[kind];
}
static unsigned bits(SemaTypeKind kind) {
  return kind <= SEMA_USHRT ? 16 : kind <= SEMA_UINT ? 32 : 64;
}
static int signed_integer(SemaTypeKind kind) {
  return kind == SEMA_SHRT || kind == SEMA_INT || kind == SEMA_LNG;
}
static void signature(FILE *out, const IrFunction *f) {
  fprintf(out, "%s brf_%s(", ctype(f->return_type), f->name);
  int comma = 0;
  for (size_t j = 0; j < f->parameter_count; j++) {
    if (f->variables[j] == SEMA_UNIT)
      continue;
    fprintf(out, "%s%s brt_var_%zu", comma ? ", " : "", ctype(f->variables[j]),
            j);
    comma = 1;
  }
  if (!comma)
    fputs("void", out);
  fputc(')', out);
}
static void binary(FILE *out, const IrInstruction *in) {
  BinaryOp op = in->as.binary;
  const char *operators[] = {"+",  "-", "*",  "/",  "%",  NULL, "==",
                             "!=", "<", "<=", ">",  ">=", NULL, NULL,
                             "&",  "|", "^",  NULL, NULL};
  const char *helpers[] = {"add", "sub", "mul", "div",    "rem",   "pow", NULL,
                           NULL,  NULL,  NULL,  NULL,     NULL,    NULL,  NULL,
                           NULL,  NULL,  NULL,  "lshift", "rshift"};
  if (in->type >= SEMA_SHRT && in->type <= SEMA_ULNG && helpers[op])
    fputs("  brt_locate(__FILE__, __LINE__);", out);
  fprintf(out, "  brt_tmp_%zu = ", in->result);
  if (in->type == SEMA_UNIT) {
    fputs(op == BINARY_EQ ? "1" : "0", out);
  } else if (in->type >= SEMA_SHRT && in->type <= SEMA_ULNG && helpers[op]) {
    fprintf(out, "(%s)brt_%s_%c(brt_tmp_%zu, brt_tmp_%zu, %u)", ctype(in->type),
            helpers[op], signed_integer(in->type) ? 's' : 'u', in->a, in->b,
            bits(in->type));
  } else if (op == BINARY_POW)
    fprintf(out, "%s(brt_tmp_%zu, brt_tmp_%zu)",
            in->type == SEMA_FLT ? "powf" : "pow", in->a, in->b);
  else if (op == BINARY_DIV && (in->type == SEMA_FLT || in->type == SEMA_DUB))
    fprintf(out, "brt_div_%s(brt_tmp_%zu, brt_tmp_%zu)",
            in->type == SEMA_FLT ? "flt" : "dub", in->a, in->b);
  else
    fprintf(out, "brt_tmp_%zu %s brt_tmp_%zu", in->a, operators[op], in->b);
  fputs(";\n", out);
}
int emit_c(FILE *out, const IrProgram *p) {
  fputs("/* Generated by Brief. Self-contained C11; link with -lm. */\n", out);
  fwrite(brief_runtime_text, 1, sizeof(brief_runtime_text) - 1, out);
  fputc('\n', out);
  for (size_t i = 0; i < p->count; i++) {
    signature(out, &p->functions[i]);
    fputs(";\n", out);
  }
  for (size_t i = 0; i < p->count; i++) {
    const IrFunction *f = &p->functions[i];
    line(out, f->span);
    signature(out, f);
    fputs(" {\n", out);
    for (size_t j = 0; j < f->variable_count; j++) {
      if (f->variables[j] == SEMA_UNIT || f->variables[j] == SEMA_NEVER)
        continue;
      if (j >= f->parameter_count)
        fprintf(out, "  %s brt_var_%zu = {0};\n", ctype(f->variables[j]), j);
      fprintf(out, "  (void)brt_var_%zu;\n", j);
    }
    for (size_t j = 0; j < f->temporaries; j++)
      fprintf(out, "  %s brt_tmp_%zu = {0};\n  (void)brt_tmp_%zu;\n",
              ctype(f->temporary_types[j]), j, j);
    for (size_t j = 0; j < f->count; j++) {
      const IrInstruction *in = &f->instructions[j];
      line(out, in->span);
      switch (in->op) {
      case IR_STRING: {
        size_t id = in->result;
        fprintf(out, "  static const unsigned char brt_bytes_%zu[] = ", id);
        string_literal(out, in->as.string.bytes, in->as.string.length);
        fputs(";\n", out);
        fprintf(out,
                "  static const brt_string brt_literal_%zu = {{0, NULL}, %zu, "
                "brt_bytes_%zu};\n  brt_tmp_%zu = &brt_literal_%zu;\n",
                id, in->as.string.length, id, id, id);
        break;
      }
      case IR_CONSTANT:
        fprintf(out, "  brt_tmp_%zu = ", in->result);
        if (in->type == SEMA_FLT || in->type == SEMA_DUB)
          fprintf(out, "%a%s", in->as.constant.real,
                  in->type == SEMA_FLT ? "f" : "");
        else if (in->as.constant.negative && in->as.constant.integer)
          fprintf(out, "(-INT64_C(%" PRIu64 ") - INT64_C(1))",
                  in->as.constant.integer - 1);
        else
          fprintf(out, "UINT64_C(%" PRIu64 ")", in->as.constant.integer);
        fputs(";\n", out);
        break;
      case IR_CALL: {
        fputs("  ", out);
        if (in->result != IR_NO_VALUE)
          fprintf(out, "brt_tmp_%zu = ", in->result);
        if (in->as.call.builtin)
          fputs("brt_print(", out);
        else
          fprintf(out, "brf_%s(", p->functions[in->as.call.function].name);
        int comma = 0;
        for (size_t k = 0; k < in->as.call.count; k++)
          if (in->as.call.args[k] != IR_NO_VALUE) {
            fprintf(out, "%sbrt_tmp_%zu", comma ? ", " : "",
                    in->as.call.args[k]);
            comma = 1;
          }
        fputs(");\n", out);
        break;
      }
      case IR_RETURN:
        if (in->a == IR_NO_VALUE)
          fputs("  return;\n", out);
        else
          fprintf(out, "  return brt_tmp_%zu;\n", in->a);
        break;
      case IR_LOAD:
        fprintf(out, "  brt_tmp_%zu = brt_var_%zu;\n", in->result, in->a);
        break;
      case IR_STORE:
        fprintf(out, "  brt_var_%zu = brt_tmp_%zu;\n", in->a, in->b);
        break;
      case IR_COPY:
        fprintf(out, "  brt_tmp_%zu = brt_tmp_%zu;\n", in->result, in->a);
        break;
      case IR_BINARY:
        binary(out, in);
        break;
      case IR_UNARY:
        if (in->as.unary == UNARY_NEG && in->type >= SEMA_SHRT &&
            in->type <= SEMA_ULNG)
          fputs("  brt_locate(__FILE__, __LINE__);", out);
        fprintf(out, "  brt_tmp_%zu = ", in->result);
        if (in->as.unary == UNARY_NEG && in->type >= SEMA_SHRT &&
            in->type <= SEMA_ULNG)
          fprintf(out, "(%s)brt_neg_%c(brt_tmp_%zu, %u)", ctype(in->type),
                  signed_integer(in->type) ? 's' : 'u', in->a, bits(in->type));
        else if (in->as.unary == UNARY_BIT_NOT && !signed_integer(in->type))
          fprintf(out, "(%s)brt_not_u(brt_tmp_%zu, %u)", ctype(in->type), in->a,
                  bits(in->type));
        else
          fprintf(out, "%cbrt_tmp_%zu",
                  in->as.unary == UNARY_NEG   ? '-'
                  : in->as.unary == UNARY_NOT ? '!'
                                              : '~',
                  in->a);
        fputs(";\n", out);
        break;
      case IR_LABEL:
        fprintf(out, "brt_label_%zu: ;\n", in->label);
        break;
      case IR_JUMP:
        fprintf(out, "  goto brt_label_%zu;\n", in->label);
        break;
      case IR_BRANCH_FALSE:
        fprintf(out, "  if (!brt_tmp_%zu) goto brt_label_%zu;\n", in->a,
                in->label);
        break;
      case IR_UNREACHABLE:
        fputs("  brt_locate(__FILE__, __LINE__); brt_panic(\"unreachable "
              "control flow\");\n",
              out);
        break;
      }
    }
    fputs("}\n\n", out);
  }
  fputs("#line 1 \"<brief entry>\"\nint main(void) {\n", out);
  fprintf(out, "  brf_%s();\n", p->functions[p->entry].name);
  fputs("  if (fflush(stdout) == EOF) {\n    fputs(\"error: cannot flush "
        "standard output\\n\", stderr);\n    return 1;\n  }\n  return 0;\n}\n",
        out);
  return !ferror(out);
}
